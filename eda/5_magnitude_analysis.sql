/*
===============================================================================
Magnitude Analysis
===============================================================================
Purpose:
    Measure and compare business metrics across different dimensions,
    including countries, customer genders, product categories, and customers.

    Understand how business metrics are distributed across different 
    dimensions.

The difference between Measures and Magnitude is important:
    - Measures: Total revenue is €X.
    - Magnitude: Category A generates €Y, Category B generates €Z.

The question you're answering: How are business metrics distributed across 
different business dimensions?

===============================================================================
*/;

-- Find the total customers by countries
SELECT 
    country,
    COUNT(*) AS total_customers
FROM gold.dim_customers
GROUP BY country
ORDER BY total_customers DESC;


-- Find total customers by gender
SELECT
    gender,
    COUNT(*) AS total_customers
FROM gold.dim_customers
GROUP BY gender
ORDER BY total_customers DESC;


-- Find total products by category
SELECT
    category,
    COUNT(*) AS total_products
FROM gold.dim_products
GROUP BY category
ORDER BY total_products DESC;


-- What is the average costs in each category?
SELECT
    category,
    AVG(cost) AS average_cost
FROM gold.dim_products
GROUP BY category
ORDER BY average_cost DESC;


-- What is the total revenue generated for each category
SELECT 
    dp.category,
    SUM(fs.sales_amount) AS total_revenue
FROM gold.fact_sales as fs
LEFT JOIN gold.dim_products as dp
    ON fs.product_key = dp.product_key
GROUP BY dp.category
ORDER BY total_revenue DESC;


-- What is the total revenue generated by each customer?
SELECT 
    dc.customer_key,
    dc.first_name,
    dc.last_name,
    SUM(fs.sales_amount) AS total_revenue
FROM gold.fact_sales as fs
LEFT JOIN gold.dim_customers as dc
    ON fs.customer_key = dc.customer_key
GROUP BY dc.customer_key, dc.first_name, dc.last_name
ORDER BY total_revenue DESC;


-- What is the distribution of sold items across countries?
SELECT 
    dc.country,
    SUM(fs.quantity) as total_distribution
FROM gold.fact_sales as fs
LEFT JOIN gold.dim_customers as dc
    ON fs.customer_key = dc.customer_key
GROUP BY dc.country
ORDER BY total_distribution DESC;
